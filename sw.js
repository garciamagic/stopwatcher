// Stopwatcher service worker: lets Android install it as a full-screen app.
// Always tries the network first, so updates on GitHub show up right away;
// falls back to the saved copy only when there's no connection.
const CACHE = 'stopwatcher-v1';
self.addEventListener('install', e => self.skipWaiting());
self.addEventListener('activate', e => e.waitUntil(self.clients.claim()));
self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  e.respondWith(
    fetch(req).then(res => {
      const copy = res.clone();
      caches.open(CACHE).then(c => c.put(req, copy));
      return res;
    }).catch(() => caches.match(req).then(r => r || caches.match('./')))
  );
});
